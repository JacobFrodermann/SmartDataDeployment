-- Replay / resume fields for SmartDataJobs (replay-fields.md, replay-fields-summary.md).
--
-- Adds run identity, lineage, input snapshots and result-TTL bookkeeping to
-- datajobs_log, policy fields to datajobs and datajobs_chain, and migrates the
-- existing log rows so they become addressable by runid.
--
-- Mirrors the collection definitions in
-- SmartDataJobs/web/data/admin/presets/base.json (preset "SmartDataJobs Base
-- tables") so a fresh preset install and this migration produce the same
-- schema. Two deliberate deviations, both enforced there as well:
--   * resultttlbasis / resultscope / onerror are plain varchar (no length),
--     because SmartData's collection create only emits a quoted DEFAULT for
--     the unparameterised varchar type (a varchar(16) would generate
--     "DEFAULT wallclock" instead of "DEFAULT 'wallclock'" and fail).
--   * The indexes below cannot be created through the preset (cdefs has no
--     index support); fresh installs simply lack them until this file is run.
--
-- runstate vocabulary:  scheduled|running|finished|failed|error|timeout|
--                        stopped|skipped|replayed
-- errorclass vocabulary: network|http_4xx|http_5xx|timeout|exec|misconfigured|
--                        dependency|internal
--
-- The ttl/scope/onerror columns are NOT NULL with their default so inserts
-- that do not name them (current SmartDataJobs, SmartData REST) keep working
-- between this migration and the code adaptation. runid/chainrunid/runstate/
-- input etc. stay nullable: the runner mints and fills them (§3.2
-- replay-fields.md: "run_id must be generated by the runner, never by the
-- database").

-- 1. datajobs: per-definition replay / reuse policy (defaults are the safe end)
ALTER TABLE smartmonitoring.datajobs
    ADD COLUMN IF NOT EXISTS idempotent      bool    NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS reusable        bool    NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS resultttlsecs   int4    NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS resultttlbasis varchar NOT NULL DEFAULT 'wallclock',
    ADD COLUMN IF NOT EXISTS resultscope     varchar NOT NULL DEFAULT 'chainrun',
    ADD COLUMN IF NOT EXISTS maxchaindepth   int4    NOT NULL DEFAULT 0;

-- 2. datajobs_chain: per-edge policy (skip = today's behaviour)
ALTER TABLE smartmonitoring.datajobs_chain
    ADD COLUMN IF NOT EXISTS onerror          varchar NOT NULL DEFAULT 'skip',
    ADD COLUMN IF NOT EXISTS reuseallowed     bool    NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS maxageresultsecs int4,
    ADD COLUMN IF NOT EXISTS propagateinput   bool    NOT NULL DEFAULT true,
    ADD COLUMN IF NOT EXISTS maxretries      int4    NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS retrydelaysecs  int4    NOT NULL DEFAULT 0;

-- 3. datajobs_log: run identity, lineage, input snapshot, TTL record
ALTER TABLE smartmonitoring.datajobs_log
    ADD COLUMN IF NOT EXISTS runid            uuid,
    ADD COLUMN IF NOT EXISTS chainrunid       uuid,
    ADD COLUMN IF NOT EXISTS parentrunid      uuid,
    ADD COLUMN IF NOT EXISTS step             int4  NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS runstate         varchar(32),
    ADD COLUMN IF NOT EXISTS input            text,
    ADD COLUMN IF NOT EXISTS inputhash        varchar(64),
    ADD COLUMN IF NOT EXISTS errorclass       varchar(64),
    ADD COLUMN IF NOT EXISTS attempt          int4  NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS replayofrunid    uuid,
    ADD COLUMN IF NOT EXISTS replayreason     varchar(255),
    ADD COLUMN IF NOT EXISTS resultvaliduntil timestamptz,
    ADD COLUMN IF NOT EXISTS resultreused      bool  NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS inputfromrunid   uuid,
    ADD COLUMN IF NOT EXISTS durationms       int4;

-- 4. Replay lookup indexes (per the summary's index list)
CREATE INDEX IF NOT EXISTS datajobs_log_chainrunid_step_idx
    ON smartmonitoring.datajobs_log (chainrunid, step);
CREATE INDEX IF NOT EXISTS datajobs_log_runid_idx
    ON smartmonitoring.datajobs_log (runid);
CREATE INDEX IF NOT EXISTS datajobs_log_parentrunid_idx
    ON smartmonitoring.datajobs_log (parentrunid);
CREATE INDEX IF NOT EXISTS datajobs_log_resultvaliduntil_idx
    ON smartmonitoring.datajobs_log (resultvaliduntil)
    WHERE resultvaliduntil IS NOT NULL;

-- 5. Migrate existing rows (replay-fields.md §3.2): every old row becomes its
--    own chain run (guessing a common chainRunId would be worse than "unknown");
--    runstate is derived from iserror/wastimeout/result->>'state'. Idempotent:
--    only rows without runid are touched, so this can run again safely.
--    resultvaliduntil stays NULL: reusable defaults to false, so the old
--    results are never reused anyway.
UPDATE smartmonitoring.datajobs_log
   SET runid      = gen_random_uuid(),
       step      = 0,
       attempt   = 1,
       runstate  = CASE
                       WHEN result ILIKE '%"state":"stopped"%' THEN 'stopped'
                       WHEN wastimeout                          THEN 'timeout'
                       WHEN iserror                             THEN 'failed'
                       ELSE 'finished'
                   END
 WHERE runid IS NULL;

-- chainrunid must equal the freshly minted runid. A single UPDATE cannot
-- reference the new runid (SET expressions see the OLD row), hence the
-- second sweep. Idempotent as well.
UPDATE smartmonitoring.datajobs_log
   SET chainrunid = runid
 WHERE runid IS NOT NULL
   AND chainrunid IS NULL;
